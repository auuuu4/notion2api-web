"""Lightweight in-process metrics for dashboards and Prometheus scraping.

The proxy is a single process, so a tiny in-memory registry keeps this free of
third-party dependencies: counters, gauges and fixed-bucket histograms behind a
lock. Values reset on restart; the SQLite request log remains the long-term
history. Prometheus text format is generated by MetricsRegistry.prometheus_text().
"""
from __future__ import annotations

import threading
from typing import Dict, Iterable, List, Optional, Tuple

DEFAULT_BUCKETS: Tuple[float, ...] = (0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 30.0, 60.0, 120.0, 300.0)

LabelKey = Tuple[Tuple[str, str], ...]


def _labels_key(labels: Dict[str, str]) -> LabelKey:
    return tuple(sorted((str(name), str(value)) for name, value in labels.items()))


def _format_labels(key: LabelKey, extra: Optional[Dict[str, str]] = None) -> str:
    items = list(key) + sorted((str(name), str(value)) for name, value in (extra or {}).items())
    if not items:
        return ""
    def _escape(value: str) -> str:
        return (str(value).replace("\\", "\\\\")
                .replace("\n", "\\n")
                .replace("\r", "\\r")
                .replace('"', '\\"'))

    rendered = ",".join('%s="%s"' % (name, _escape(value)) for name, value in items)
    return "{" + rendered + "}"


class MetricsRegistry:
    """Thread-safe counter/gauge/histogram registry."""

    def __init__(self, buckets: Iterable[float] = DEFAULT_BUCKETS) -> None:
        self._lock = threading.Lock()
        self._counters: Dict[Tuple[str, LabelKey], float] = {}
        self._gauges: Dict[Tuple[str, LabelKey], float] = {}
        self._histograms: Dict[Tuple[str, LabelKey], Dict[str, object]] = {}
        self._help: Dict[str, str] = {}
        self._buckets = tuple(sorted(float(b) for b in buckets))

    # -- writers ---------------------------------------------------------
    def describe(self, name: str, help_text: str) -> None:
        with self._lock:
            self._help.setdefault(name, help_text)

    def inc(self, name: str, value: float = 1.0, **labels: str) -> None:
        key = (name, _labels_key(labels))
        with self._lock:
            self._counters[key] = self._counters.get(key, 0.0) + float(value)

    def set_gauge(self, name: str, value: float, **labels: str) -> None:
        key = (name, _labels_key(labels))
        with self._lock:
            self._gauges[key] = float(value)

    def observe(self, name: str, value: float, **labels: str) -> None:
        key = (name, _labels_key(labels))
        with self._lock:
            entry = self._histograms.get(key)
            if entry is None:
                entry = {"counts": [0] * len(self._buckets), "sum": 0.0, "count": 0, "inf": 0}
                self._histograms[key] = entry
            numeric = float(value)
            counts: List[int] = entry["counts"]  # type: ignore[assignment]
            placed = False
            for index, bound in enumerate(self._buckets):
                if numeric <= bound:
                    counts[index] += 1
                    placed = True
                    break
            if not placed:
                entry["inf"] = int(entry.get("inf", 0)) + 1  # type: ignore[arg-type]
            entry["sum"] = float(entry["sum"]) + numeric
            entry["count"] = int(entry["count"]) + 1

    # -- readers ---------------------------------------------------------
    def snapshot(self) -> Dict[str, object]:
        with self._lock:
            counters = [
                {"name": name, "labels": dict(key), "value": value}
                for (name, key), value in sorted(self._counters.items())
            ]
            gauges = [
                {"name": name, "labels": dict(key), "value": value}
                for (name, key), value in sorted(self._gauges.items())
            ]
            histograms = []
            for (name, key), entry in sorted(self._histograms.items()):
                counts: List[int] = entry["counts"]  # type: ignore[assignment]
                histograms.append(
                    {
                        "name": name,
                        "labels": dict(key),
                        "buckets": [
                            {"le": bound, "count": counts[index]}
                            for index, bound in enumerate(self._buckets)
                        ],
                        "inf": int(entry.get("inf", 0)),
                        "sum": float(entry["sum"]),
                        "count": int(entry["count"]),
                    }
                )
            return {"counters": counters, "gauges": gauges, "histograms": histograms}

    def prometheus_text(self, extra_gauges: Optional[List[Tuple[str, float, Dict[str, str]]]] = None) -> str:
        """Render counters, gauges and histograms in Prometheus text format 0.0.4."""
        lines: List[str] = []
        with self._lock:
            counters = dict(self._counters)
            gauges = dict(self._gauges)
            histograms = {key: dict(entry) for key, entry in self._histograms.items()}
            help_texts = dict(self._help)

        emitted_types = set()

        def _emit_type(name: str, metric_type: str) -> None:
            key = (name, metric_type)
            if key in emitted_types:
                return
            emitted_types.add(key)
            lines.append("# HELP %s %s" % (name, help_texts.get(name, name)))
            lines.append("# TYPE %s %s" % (name, metric_type))

        for name in sorted({key[0] for key in counters}):
            _emit_type(name, "counter")
            for (metric_name, key), value in sorted(counters.items()):
                if metric_name != name:
                    continue
                lines.append("%s%s %s" % (name, _format_labels(key), _format_number(value)))

        for name in sorted({key[0] for key in gauges}):
            _emit_type(name, "gauge")
            for (metric_name, key), value in sorted(gauges.items()):
                if metric_name != name:
                    continue
                lines.append("%s%s %s" % (name, _format_labels(key), _format_number(value)))

        for name, value, labels in (extra_gauges or []):
            if name not in {key[0] for key in gauges}:
                _emit_type(name, "gauge")
            lines.append("%s%s %s" % (name, _format_labels(_labels_key(labels)), _format_number(value)))

        for name in sorted({key[0] for key in histograms}):
            _emit_type(name, "histogram")
            for (metric_name, key), entry in sorted(histograms.items()):
                if metric_name != name:
                    continue
                counts: List[int] = entry["counts"]  # type: ignore[assignment]
                cumulative = 0
                for index, bound in enumerate(self._buckets):
                    cumulative += counts[index]
                    labels = _format_labels(key, {"le": _format_number(bound)})
                    lines.append("%s_bucket%s %s" % (name, labels, cumulative))
                cumulative += int(entry.get("inf", 0))
                labels = _format_labels(key, {"le": "+Inf"})
                lines.append("%s_bucket%s %s" % (name, labels, cumulative))
                lines.append("%s_sum%s %s" % (name, _format_labels(key), _format_number(float(entry["sum"]))))
                lines.append("%s_count%s %s" % (name, _format_labels(key), int(entry["count"])))
        return "\n".join(lines) + ("\n" if lines else "")


def _format_number(value: float) -> str:
    numeric = float(value)
    if numeric == int(numeric) and abs(numeric) < 1e15:
        return str(int(numeric))
    return repr(numeric)


# Process-wide registry. Import this object everywhere so scrape and writers agree.
metrics = MetricsRegistry()


def inc(name: str, value: float = 1.0, **labels: str) -> None:
    metrics.inc(name, value, **labels)


def set_gauge(name: str, value: float, **labels: str) -> None:
    metrics.set_gauge(name, value, **labels)


def observe(name: str, value: float, **labels: str) -> None:
    metrics.observe(name, value, **labels)
