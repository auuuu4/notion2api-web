"""Alignment matrix e2e runner (mock Notion upstream + real proxy + real DSH).

Each case is executed by the real headless DSH harness against the real proxy; the
only replaced component is Notion's runInferenceTranscript, which replays the
scripted official NDJSON shapes from matrix_cases.json. Assertions cover:

* the harness actually executed the translated tool (DSH tool_call + tool_result);
* the next request replayed assistant tool_use + agent-tool-result entries into
  the Notion transcript (official replay, no user-text flatten);
* record-map echoes of the replayed entries did NOT become new tool calls
  (runaway-echo regression);
* workspace files / final answers are what the case expects.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from typing import Any, Dict, List

MATRIX_DIR = os.path.dirname(os.path.abspath(__file__))
CASES_PATH = os.path.join(MATRIX_DIR, "matrix_cases.json")
RUN_HEADLESS = os.path.join(MATRIX_DIR, "run-headless.ps1")
# Work dir holds generated workspaces / evidence / mock records / proxy capture.
# It can be pointed anywhere (default: scripts/alignment_matrix/_work).
WORK_DIR = os.environ.get("MATRIX_WORK_DIR") or os.path.join(MATRIX_DIR, "_work")
WORKSPACE_ROOT = os.path.join(WORK_DIR, "workspace")
EVIDENCE_ROOT = os.path.join(WORK_DIR, "evidence")
MOCK_RECORD_INDEX = os.path.join(WORK_DIR, "mock-records", "index.jsonl")
PROXY_CAPTURE_DIR = os.path.join(WORK_DIR, "capture")
